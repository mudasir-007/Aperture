/**
 * Brute-force cosine similarity. This is the MVP's vector-search
 * implementation: fine for a
 * small-to-medium corpus scanned per organization; the retrieval service
 * interface is the seam to swap in pgvector/a dedicated ANN index later
 * without touching callers.
 */
export function cosineSimilarity(a: number[], b: number[]): number {
  if (a.length !== b.length) {
    throw new Error(`Vector length mismatch: ${a.length} vs ${b.length}`);
  }

  let dot = 0;
  let normA = 0;
  let normB = 0;

  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }

  if (normA === 0 || normB === 0) {
    return 0;
  }

  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
